#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_all_locales_and_keys_non_empty() {
        for locale in UiLocale::all() {
            assert!(!locale.code().is_empty());
            assert!(!locale.native_name().is_empty());
            for &key in TextKey::ALL {
                let s = t_in(locale, key);
                assert!(
                    !s.trim().is_empty(),
                    "empty translation for {:?} in {:?}",
                    key,
                    locale
                );
            }
        }
        set_active_locale(UiLocale::Es);
        assert_eq!(edge_relation_label(&EdgeRelation::Supports), "respalda");
        assert_eq!(weekday_short(0), "Lun");
        assert_eq!(weekday_narrow(2), "X");
        assert_eq!(month_short(1), "Ene");
        assert_eq!(dock_position_label(DockPosition::Top), "Arriba");
        set_active_locale(UiLocale::En);
        assert_eq!(edge_relation_label(&EdgeRelation::Supports), "supports");
        assert_eq!(weekday_short(0), "Mon");
    }
}
