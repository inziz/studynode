#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, Default)]
pub enum UiLocale {
    #[default]
    En,
    Es,
    Fr,
    De,
    Pt,
    Ja,
}

impl UiLocale {
    pub const fn all() -> [UiLocale; 6] {
        [
            UiLocale::En,
            UiLocale::Es,
            UiLocale::Fr,
            UiLocale::De,
            UiLocale::Pt,
            UiLocale::Ja,
        ]
    }

    pub const fn code(self) -> &'static str {
        match self {
            UiLocale::En => "en",
            UiLocale::Es => "es",
            UiLocale::Fr => "fr",
            UiLocale::De => "de",
            UiLocale::Pt => "pt",
            UiLocale::Ja => "ja",
        }
    }

    pub const fn short_label(self) -> &'static str {
        match self {
            UiLocale::En => "EN",
            UiLocale::Es => "ES",
            UiLocale::Fr => "FR",
            UiLocale::De => "DE",
            UiLocale::Pt => "PT",
            UiLocale::Ja => "JA",
        }
    }

    pub const fn native_name(self) -> &'static str {
        match self {
            UiLocale::En => "English",
            UiLocale::Es => "Español",
            UiLocale::Fr => "Français",
            UiLocale::De => "Deutsch",
            UiLocale::Pt => "Português",
            UiLocale::Ja => "日本語",
        }
    }

    pub const fn english_name(self) -> &'static str {
        match self {
            UiLocale::En => "English",
            UiLocale::Es => "Spanish",
            UiLocale::Fr => "French",
            UiLocale::De => "German",
            UiLocale::Pt => "Portuguese",
            UiLocale::Ja => "Japanese",
        }
    }

    pub const fn key_suffix(self) -> &'static str {
        self.code()
    }

    const fn as_u8(self) -> u8 {
        match self {
            UiLocale::En => 0,
            UiLocale::Es => 1,
            UiLocale::Fr => 2,
            UiLocale::De => 3,
            UiLocale::Pt => 4,
            UiLocale::Ja => 5,
        }
    }

    const fn from_u8(v: u8) -> Self {
        match v {
            1 => UiLocale::Es,
            2 => UiLocale::Fr,
            3 => UiLocale::De,
            4 => UiLocale::Pt,
            5 => UiLocale::Ja,
            _ => UiLocale::En,
        }
    }
}

static ACTIVE_LOCALE: AtomicU8 = AtomicU8::new(0);

#[inline]
pub fn active_locale() -> UiLocale {
    UiLocale::from_u8(ACTIVE_LOCALE.load(Ordering::Relaxed))
}

#[inline]
pub fn set_active_locale(locale: UiLocale) {
    ACTIVE_LOCALE.store(locale.as_u8(), Ordering::Relaxed);
}

